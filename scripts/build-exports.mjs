// Generates the public package surface from the component barrels:
//   1. src/lib/index.ts — root barrel of unambiguous exports
//   2. package.json "exports" — root, per-component subpaths, theme.css
// Run via `pnpm package` (after `pnpm registry`).
import { readFileSync, writeFileSync, existsSync } from "node:fs"
import { join, dirname } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const registryPath = join(root, "src/lib/registry.json")
if (!existsSync(registryPath)) {
  console.error("registry.json missing — run `pnpm registry` first")
  process.exit(1)
}
const registry = JSON.parse(readFileSync(registryPath, "utf8"))

function parseBarrel(source) {
  const values = []
  const types = []
  for (const match of source.matchAll(/export\s+(type\s+)?\{([^}]+)\}\s+from/g)) {
    const isType = Boolean(match[1])
    for (const part of match[2].split(",")) {
      const spec = part.trim()
      if (!spec) continue
      const inlineType = spec.startsWith("type ")
      const name = spec
        .replace(/^type\s+/, "")
        .split(/\s+as\s+/)
        .pop()
        .trim()
      if (!name) continue
      ;(isType || inlineType ? types : values).push(name)
    }
  }
  return { values, types }
}

const barrels = registry.components.map((component) => {
  const source = readFileSync(
    join(root, "src/lib/components", component.slug, "index.ts"),
    "utf8",
  )
  return { slug: component.slug, ...parseBarrel(source) }
})

// A name exported by several barrels (ListData, CalendarGrid, ...) is
// ambiguous at the root; it stays reachable through its component subpath.
const counts = new Map()
for (const barrel of barrels) {
  for (const name of [...barrel.values, ...barrel.types]) {
    counts.set(name, (counts.get(name) ?? 0) + 1)
  }
}

const lines = [
  "// Generated by scripts/build-exports.mjs — do not edit.",
  "// Names shared by several components live on their subpath only.",
]
let exported = 0
for (const barrel of barrels) {
  const values = barrel.values.filter((name) => counts.get(name) === 1)
  const types = barrel.types.filter((name) => counts.get(name) === 1)
  if (values.length)
    lines.push(`export { ${values.join(", ")} } from "./components/${barrel.slug}"`)
  if (types.length)
    lines.push(
      `export type { ${types.join(", ")} } from "./components/${barrel.slug}"`,
    )
  exported += values.length + types.length
}
writeFileSync(join(root, "src/lib/index.ts"), lines.join("\n") + "\n")

const pkgPath = join(root, "package.json")
const pkg = JSON.parse(readFileSync(pkgPath, "utf8"))
const entry = (slug) => ({
  types: `./dist/components/${slug}/index.d.ts`,
  svelte: `./dist/components/${slug}/index.js`,
  default: `./dist/components/${slug}/index.js`,
})
pkg.exports = {
  ".": {
    types: "./dist/index.d.ts",
    svelte: "./dist/index.js",
    default: "./dist/index.js",
  },
  ...Object.fromEntries(
    registry.components.map((c) => [`./${c.slug}`, entry(c.slug)]),
  ),
  "./theme.css": "./dist/theme.css",
  "./package.json": "./package.json",
}
writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + "\n")
console.log(
  `exports: root barrel (${exported} names) + ${registry.components.length} subpaths + theme.css`,
)